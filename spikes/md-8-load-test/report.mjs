const cpuPct = (m, p, dt) =>
  (100 * (m.process_cpu_seconds_total - p.process_cpu_seconds_total)) / dt;
function compare(scenario, file, title, subtitle, xLabel, yLabel, fn, t0Of, extra = {}) {
  const sers = variants
    .map(({ v, short: name, slot }) => {
      const r = medianRun(`${v}-${scenario}`);
      return (
        r && {
          name,
          slot,
          points: extra.smoothS
            ? smooth(series(r, fn, t0Of(r)), extra.smoothS)
            : series(r, fn, t0Of(r)),
        }
      );
    })
    .filter(Boolean);
  if (sers.length) lineChart({ file, title, subtitle, xLabel, yLabel, series: sers, ...extra });
}
