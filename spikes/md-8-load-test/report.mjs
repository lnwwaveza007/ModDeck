const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;");
function niceMax(v) {
  if (v <= 0) return 1;
  const p = 10 ** Math.floor(Math.log10(v));
  for (const m of [1, 1.2, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10]) if (m * p >= v) return m * p;
  return 10 * p;
}
function niceTicks(min, max, n = 6) {
  const raw = (max - min) / n;
  const p = 10 ** Math.floor(Math.log10(raw));
  const step = [1, 2, 2.5, 5, 10].map((m) => m * p).find((m) => m >= raw);
  const out = [];
  for (let v = Math.ceil(min / step) * step; v <= max + 1e-9; v += step) out.push(+v.toFixed(6));
  return out;
}
const fmtTick = (v) => (v >= 1000 ? `${+(v / 1000).toFixed(1)}k` : `${+v.toFixed(v < 10 ? 1 : 0)}`);

function niceStep(raw) {
  const p = 10 ** Math.floor(Math.log10(raw));
  return [1, 2, 2.5, 5, 10].map((m) => m * p).find((m) => m >= raw);
}
function frame({ title, subtitle, yLabel, W = 760, H = 340, yMax: rawMax }) {
  const step = niceStep(rawMax / 4);
  const yMax = Math.ceil(rawMax / step - 1e-9) * step;
  const yTicks = Array.from(
    { length: Math.round(yMax / step) + 1 },
    (_, i) => +(i * step).toFixed(6),
  );
  const M = { l: 64, r: 150, t: 76, b: 48 };
  const iw = W - M.l - M.r;
  const ih = H - M.t - M.b;
  const y = (v) => M.t + ih - (v / yMax) * ih;
  let s = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${esc(title)}">${STYLE}
  <rect class="bg" width="${W}" height="${H}" rx="8"/>
  <text class="t1" x="${M.l}" y="26" font-size="16" font-weight="600">${esc(title)}</text>
  <text class="t2" x="${M.l}" y="46" font-size="12">${esc(subtitle)}</text>`;
  for (const tv of yTicks) {
    s += `<line class="grid" x1="${M.l}" x2="${M.l + iw}" y1="${y(tv)}" y2="${y(tv)}" stroke-width="1"/>`;
    s += `<text class="t2" x="${M.l - 8}" y="${y(tv) + 4}" font-size="11" text-anchor="end">${fmtTick(tv)}</text>`;
  }
  s += `<text class="t2" transform="translate(16 ${M.t + ih / 2}) rotate(-90)" font-size="11" text-anchor="middle">${esc(yLabel)}</text>`;
  return { s, M, iw, ih, y, W, H, yMax };
}

function threshold(fr, value, label) {
  const yy = fr.y(value);
  return `<line class="thr" x1="${fr.M.l}" x2="${fr.M.l + fr.iw}" y1="${yy}" y2="${yy}" stroke-width="1.5" stroke-dasharray="5 4"/>
  <text class="t2" x="${fr.M.l + fr.iw + 8}" y="${yy + 4}" font-size="11">${esc(label)}</text>`;
}

function lineChart({
  file,
  title,
  subtitle,
  xLabel,
  yLabel,
  series,
  xMin,
  xMax,
  yMax,
  thresholdAt,
  thresholdLabel,
  xMarkerAt,
  xMarkerLabel,
  xFmt = (v) => fmtTick(v),
}) {
  const all = series.flatMap((s) => s.points);
  xMin ??= Math.min(...all.map((p) => p[0]));
  xMax ??= Math.max(...all.map((p) => p[0]));
  yMax ??= Math.max(...all.map((p) => p[1]), thresholdAt ?? 0) * 1.05;
  const fr = frame({ title, subtitle, yLabel, yMax });
  yMax = fr.yMax;
  const x = (v) => fr.M.l + ((v - xMin) / (xMax - xMin || 1)) * fr.iw;
  let s = fr.s;
  for (const tv of niceTicks(xMin, xMax))
    s += `<text class="t2" x="${x(tv)}" y="${fr.M.t + fr.ih + 18}" font-size="11" text-anchor="middle">${xFmt(tv)}</text>`;
  s += `<line class="axis" x1="${fr.M.l}" x2="${fr.M.l + fr.iw}" y1="${fr.M.t + fr.ih}" y2="${fr.M.t + fr.ih}" stroke-width="1"/>`;
  s += `<text class="t2" x="${fr.M.l + fr.iw / 2}" y="${fr.H - 10}" font-size="11" text-anchor="middle">${esc(xLabel)}</text>`;
  if (thresholdAt !== undefined) s += threshold(fr, thresholdAt, thresholdLabel);
  if (xMarkerAt !== undefined && xMarkerAt <= xMax) {
    const xx = x(xMarkerAt);
    s += `<line class="thr" x1="${xx}" x2="${xx}" y1="${fr.M.t}" y2="${fr.M.t + fr.ih}" stroke-width="1.5" stroke-dasharray="5 4"/>`;
    s += `<text class="t2" x="${xx + 6}" y="${fr.M.t + 12}" font-size="11">${esc(xMarkerLabel)}</text>`;
  }
  const labelYs = [];
  series.forEach((ser, i) => {
    const pts = ser.points.filter((p) => p[0] >= xMin && p[0] <= xMax);
    if (!pts.length) return;
    const d = pts
      .map(
        (p, j) => `${j ? "L" : "M"}${x(p[0]).toFixed(1)},${fr.y(Math.min(p[1], yMax)).toFixed(1)}`,
      )
      .join("");
    s += `<path class="l${ser.slot}" d="${d}" fill="none" stroke-width="2" stroke-linejoin="round" stroke-linecap="round"/>`;
    // direct label at the right end, nudged apart
    let ly = fr.y(Math.min(pts.at(-1)[1], yMax)) + 4;
    for (const o of labelYs) if (Math.abs(o - ly) < 14) ly = o + 14;
    labelYs.push(ly);
    s += `<circle class="s${ser.slot}" cx="${fr.M.l + fr.iw + 12}" cy="${ly - 4}" r="4"/>`;
    s += `<text class="t1" x="${fr.M.l + fr.iw + 20}" y="${ly}" font-size="12">${esc(ser.name)}</text>`;
  });
  fs.writeFileSync(path.join(chartsDir, file), s + "</svg>\n");
}

function barChart({
  file,
  title,
  subtitle,
  yLabel,
  groups,
  seriesDefs,
  thresholdAt,
  thresholdLabel,
}) {
  const seriesNames = seriesDefs.map((d) => d.name);
  // groups: [{name, values:[v per series]}]
  const fr = frame({
    title,
    subtitle,
    yLabel,
    yMax:
      Math.max(...groups.flatMap((g) => g.values.filter((v) => v != null)), thresholdAt ?? 0) * 1.1,
  });
  const yMax = fr.yMax;
  let s = fr.s;
  const gw = fr.iw / groups.length;
  const bw = Math.min(56, (gw * 0.6) / seriesNames.length);
  groups.forEach((g, gi) => {
    const cx = fr.M.l + gw * gi + gw / 2;
    s += `<text class="t1" x="${cx}" y="${fr.M.t + fr.ih + 20}" font-size="12" text-anchor="middle">${esc(g.name)}</text>`;
    g.values.forEach((v, si) => {
      if (v == null) return;
      const x0 = cx - (bw * seriesNames.length + 2 * (seriesNames.length - 1)) / 2 + si * (bw + 2);
      const y0 = fr.y(Math.min(v, yMax));
      const h = fr.M.t + fr.ih - y0;
      const r = Math.min(4, h);
      // rounded top only, anchored to baseline
      s += `<path class="s${seriesDefs[si].slot}" d="M${x0},${fr.M.t + fr.ih}V${y0 + r}Q${x0},${y0} ${x0 + r},${y0}H${x0 + bw - r}Q${x0 + bw},${y0} ${x0 + bw},${y0 + r}V${fr.M.t + fr.ih}Z"/>`;
      s += `<text class="t1" x="${x0 + bw / 2}" y="${y0 - 6}" font-size="11" text-anchor="middle">${fmtTick(v)}</text>`;
    });
  });
  s += `<line class="axis" x1="${fr.M.l}" x2="${fr.M.l + fr.iw}" y1="${fr.M.t + fr.ih}" y2="${fr.M.t + fr.ih}" stroke-width="1"/>`;
  if (thresholdAt !== undefined) s += threshold(fr, thresholdAt, thresholdLabel);
  let lx = fr.M.l;
  seriesDefs.forEach((d) => {
    s += `<rect class="s${d.slot}" x="${lx}" y="55" width="10" height="10" rx="2"/>`;
    s += `<text class="t1" x="${lx + 16}" y="64" font-size="12">${esc(d.name)}</text>`;
    lx += 30 + d.name.length * 6.6;
  });
  fs.writeFileSync(path.join(chartsDir, file), s + "</svg>\n");
}

// ---- data helpers -------------------------------------------------------------------
const ofGroup = (g) => runs.filter((r) => r.group === g);
const median = (xs) => {
  const v = xs.filter((x) => x != null).sort((a, b) => a - b);
  return v.length ? v[Math.floor((v.length - 1) / 2)] : null;
};
// The run whose p95 is the median of its group: used for the per-run charts.
function medianRun(group) {
  const g = ofGroup(group);
  if (!g.length) return null;
  const m = median(g.map((r) => r.summary.latency.delivery_ms.p95));
  return g.find((r) => r.summary.latency.delivery_ms.p95 === m);
}
function samples(run) {
  return fs
    .readFileSync(path.join(run.dir, "samples.jsonl"), "utf8")
    .trim()
    .split("\n")
    .map((l) => JSON.parse(l));
}
// Per-second series derived from the scraped /metrics, summed over instances.
function series(run, fn, t0) {
  const S = samples(run);
  const out = [];
  for (let i = 1; i < S.length; i++) {
    const dt = (S[i].t - S[i - 1].t) / 1000;
    let v = 0;
    let ok = false;
    S[i].servers.forEach((s, j) => {
      const p = S[i - 1].servers[j];
      if (s.m && p?.m) {
        v += fn(s.m, p.m, dt);
        ok = true;
      }
    });
    if (ok) out.push([(S[i].t - t0) / 1000, v]);
  }
  return out;
}
// Trailing moving average over `w` samples (1 s each) for long, noisy runs.
const smooth = (pts, w) =>
  pts.map((p, i) => {
    const win = pts.slice(Math.max(0, i - w + 1), i + 1);
    return [p[0], win.reduce((a, q) => a + q[1], 0) / win.length];
  });
const rate = (k) => (m, p, dt) => (m[k] - p[k]) / dt;
const gauge =
  (k, scale = 1) =>
  (m) =>
    m[k] * scale;
function cdf(run) {
  const buckets = {};
  for (const fname of fs.readdirSync(run.dir).filter((x) => x.startsWith("raw-"))) {
    const raw = JSON.parse(fs.readFileSync(path.join(run.dir, fname), "utf8"));
    for (const [b, n] of Object.entries(raw.hist.delivery_ms)) buckets[b] = (buckets[b] ?? 0) + n;
  }
  const entries = Object.entries(buckets)
    .map(([b, n]) => [Number(b) / 10, n])
    .sort((a, b) => a[0] - b[0]);
  const total = entries.reduce((s, [, n]) => s + n, 0);
  const pts = [[0, 0]];
  let acc = 0;
  for (const [v, n] of entries) {
    acc += n;
    pts.push([v, (100 * acc) / total]);
  }
  return pts;
}

